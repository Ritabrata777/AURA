static void glyph(char c,int x,int y,int z){
    const uint8_t *col;
    if(c>=' '&&c<='~'){
        col=font5x7[c-' '];
    }else{
        col=font5x7['?'-' '];
    }
    for(int a=0;a<5;a++){
        for(int b=0;b<7;b++){
            if(col[a]&(1u<<b)){
                for(int i=0;i<z;i++)for(int j=0;j<z;j++)px(x+a*z+i,y+b*z+j);
            }
        }
    }
}
