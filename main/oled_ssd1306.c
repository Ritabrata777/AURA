// Detection is ACK-only (i2c_master_probe sends just the address byte), so a
// device is reported present only when it actually answered. Each address is
// retried: a single probe immediately after bus bring-up can race the first
// recovery cycle and otherwise would brand a healthy OLED as absent.
static bool oled_probe_address(uint8_t addr)
{
    for (int attempt = 0; attempt < 3; attempt++) {
        if (i2c_master_probe(bus, addr, 100) == ESP_OK) {
            return true;
        }
        vTaskDelay(pdMS_TO_TICKS(10));
    }
    return false;
}

void oled_ssd1306_init(void)
{
    if (!bus) return;
    mutex = xSemaphoreCreateMutex();

    static const uint8_t addrs[] = {SSD1306_I2C_ADDRESS, 0x3D};
    uint8_t found_addr = 0;
    bool found = false;
    for (int i = 0; i < (int)(sizeof(addrs)/sizeof(addrs[0])) && !found; i++) {
        if (!oled_probe_address(addrs[i])) continue;
        i2c_device_config_t c = {
            .dev_addr_length = I2C_ADDR_BIT_LEN_7,
            .device_address = addrs[i],
            .scl_speed_hz = 100000,
        };
        if (i2c_master_bus_add_device(bus, &c, &dev) != ESP_OK) continue;
        found_addr = addrs[i];
        found = true;
    }
    if (!found) {
        dev = NULL;
        ESP_LOGE(TAG, "OLED: not found at 0x3C or 0x3D (no ACK on either address)");
        return;
    }
    ESP_LOGI(TAG, "OLED: Found at 0x%02X", found_addr);

    // Datasheet bring-up sequence, including the charge-pump enable (0x8D,
    // 0x14) without which the panel stays dark even though I2C works.
    static const uint8_t a[] = {0xae,0xd5,0x80,0xa8,0x3f,0xd3,0,0x40,0x8d,0x14,
                                0xa1,0xc8,0xda,0x12,0x81,0x7f,0xd9,0xf1,0xdb,0x40,
                                0xa4,0xa6,0xaf};
    for (size_t i = 0; i < sizeof(a); i++) {
        if (command(a[i]) != ESP_OK) {
            ESP_LOGE(TAG, "OLED: init failed at command %zu", i);
            i2c_master_bus_rm_device(dev);
            dev = NULL;
            return;
        }
    }
    oled_clear();
    ESP_LOGI(TAG, "OLED: Initialization successful");
    oled_show_boot_diagnostics();
    vTaskDelay(pdMS_TO_TICKS(1000));
}
